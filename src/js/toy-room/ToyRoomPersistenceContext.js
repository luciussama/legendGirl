/** Acesso explícito aos campos persistidos e à retomada dos subsistemas. */
export function createToyRoomPersistenceContext(room) {
  return {
    get arena() { return room.arena; },
    get battle() { return room.battle; },
    get cameraX() { return room.cameraX; },
    set cameraX(value) { room.cameraX = value; },
    get cameraY() { return room.cameraY; },
    set cameraY(value) { room.cameraY = value; },
    clearInput: () => room.clearInput(),
    get fairy() { return room.fairy; },
    set fairy(value) { room.fairy = value; },
    get furniture() { return room.furniture; },
    set furniture(value) { room.furniture = value; },
    get gameplayState() { return room.gameplayState; },
    set gameplayState(value) { room.gameplayState = value; },
    get introAlpha() { return room.introAlpha; },
    set introAlpha(value) { room.introAlpha = value; },
    get introBannerTimer() { return room.introBannerTimer; },
    set introBannerTimer(value) { room.introBannerTimer = value; },
    get lastActionTime() { return room.lastActionTime; },
    set lastActionTime(value) { room.lastActionTime = value; },
    get organizedCount() { return room.organizedCount; },
    set organizedCount(value) { room.organizedCount = value; },
    get player() { return room.player; },
    set player(value) { room.player = value; },
    startTutorial: () => room.startTutorial(),
    get story() { return room.story; },
    get toyRoomTutorialCompleted() { return room.toyRoomTutorialCompleted; },
    set toyRoomTutorialCompleted(value) { room.toyRoomTutorialCompleted = value; },
    get toys() { return room.toys; },
    set toys(value) { room.toys = value; },
    get tutorial() { return room.tutorial; },
    get victoryBannerActive() { return room.victoryBannerActive; },
    set victoryBannerActive(value) { room.victoryBannerActive = value; },
    get victoryBannerTimer() { return room.victoryBannerTimer; },
    set victoryBannerTimer(value) { room.victoryBannerTimer = value; },
  };
}
